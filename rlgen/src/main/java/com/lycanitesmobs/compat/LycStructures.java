package com.lycanitesmobs.compat;

import com.mojang.datafixers.util.Pair;
import java.util.ArrayList;
import java.util.List;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Holder;
import net.minecraft.core.HolderSet;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.levelgen.structure.Structure;

/**
 * 1.12 ChunkProviderServer.getNearestStructurePos(world, name, pos, false) by 1.12 structure name. The 1.12 structures are
 * generated by rlgen (its marker structures answer /locate), the nether and end ones by vanilla.
 */
public final class LycStructures {
   private LycStructures() {
   }

   private static String[] ids(String name) {
      switch (name) {
         case "Stronghold": return new String[]{"rlgen:stronghold", "minecraft:stronghold"};
         case "Village": return new String[]{"rlgen:village"};
         case "Mineshaft": return new String[]{"rlgen:better_mineshaft", "minecraft:mineshaft"};
         case "Temple": return new String[]{"rlgen:desert_pyramid", "rlgen:jungle_pyramid", "rlgen:swamp_hut", "rlgen:igloo"};
         case "Monument": return new String[]{"rlgen:ocean_monument", "minecraft:monument"};
         case "Mansion": return new String[]{"rlgen:mansion", "minecraft:mansion"};
         case "Fortress": return new String[]{"minecraft:fortress"};
         case "EndCity": return new String[]{"minecraft:end_city"};
         default: return new String[0];
      }
   }

   public static BlockPos nearest(ServerLevel level, String name, BlockPos pos) {
      Registry<Structure> registry = level.registryAccess().registryOrThrow(Registries.STRUCTURE);
      List<Holder<Structure>> holders = new ArrayList<>();
      for (String id : ids(name)) {
         registry.getHolder(ResourceLocation.parse(id)).ifPresent(holders::add);
      }
      if (holders.isEmpty()) {
         return null;
      }
      // 1.12 MapGenStructure searched up to 100 chunks
      Pair<BlockPos, Holder<Structure>> found = level.getChunkSource().getGenerator()
         .findNearestMapStructure(level, HolderSet.direct(holders), pos, 100, false);
      return found != null ? found.getFirst() : null;
   }
}
