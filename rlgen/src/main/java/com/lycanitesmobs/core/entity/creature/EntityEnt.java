public class EntityEnt extends TameableCreatureEntity implements Enemy {
   public EntityEnt(Level world) {
      super(world);
      this.attribute = EnumCreatureAttribute.UNDEFINED;
      this.spawnsUnderground = false;
      this.hasAttackSound = true;
      this.spreadFire = true;
      this.canGrow = true;
      this.babySpawnChance = 0.1;
      this.setupMob();
   }

   @Override
   protected void initEntityAI() {
      super.initEntityAI();
      this.tasks.addTask(this.nextCombatGoalIndex++, new AttackMeleeGoal(this).setTargetClass(Player.class).setLongMemory(false));
      this.tasks.addTask(this.nextCombatGoalIndex++, new AttackMeleeGoal(this));
   }

   @Override
   public void aiStep() {
      super.aiStep();
      if (this.getAirSupply() >= 0) {
         if (this.isInWater()) {
            this.addEffect(new MobEffectInstance(MobEffects.REGENERATION, 60, 1));
         } else if (this.waterContact()) {
            this.addEffect(new MobEffectInstance(MobEffects.REGENERATION, 60, 0));
         }
      }
   }

   @Override
   public boolean canAttackEntity(LivingEntity target) {
      return target instanceof EntityTreant ? false : super.canAttackEntity(target);
   }

   @Override
   public boolean attackMelee(Entity target, double damageScale) {
      if (!super.attackMelee(target, damageScale)) {
         return false;
      } else {
         float leeching = Math.max(1.0F, this.getAttackDamage(damageScale));
         this.heal(leeching);
         return true;
      }
   }

   @Override
   public float getDamageModifier(DamageSource damageSrc) {
      if (damageSrc.is(DamageTypeTags.IS_FIRE)) {
         return 2.0F;
      } else {
         if (damageSrc.getEntity() != null) {
            ItemStack heldItem = ItemStack.EMPTY;
            if (damageSrc.getEntity() instanceof LivingEntity) {
               LivingEntity entityLiving = (LivingEntity)damageSrc.getEntity();
               if (!entityLiving.getItemInHand(InteractionHand.MAIN_HAND).isEmpty()) {
                  heldItem = entityLiving.getItemInHand(InteractionHand.MAIN_HAND);
               }
            }

            if (ObjectLists.isAxe(heldItem)) {
               return 2.0F;
            }
         }

         return super.getDamageModifier(damageSrc);
      }
   }

   @Override
   public float getFallResistance() {
      return 100.0F;
   }

   @Override
   public boolean petControlsEnabled() {
      return true;
   }

   @Override
   public int getNoBagSize() {
      return 0;
   }

   @Override
   public int getBagSize() {
      return this.creatureInfo.bagSize;
   }

   @Override
   public ResourceLocation getTexture() {
      if ("Twisted Ent".equals(this.getCustomName().getString())) {
         String textureName = this.getTextureName() + "_twisted";
         if (AssetManager.getTexture(textureName) == null) {
            AssetManager.addTexture(textureName, this.creatureInfo.modInfo, "textures/entity/" + textureName.toLowerCase() + ".png");
         }

         return AssetManager.getTexture(textureName);
      } else if ("Salty Tree".equals(this.getCustomName().getString())) {
         String textureName = this.getTextureName() + "_saltytree";
         if (AssetManager.getTexture(textureName) == null) {
            AssetManager.addTexture(textureName, this.creatureInfo.modInfo, "textures/entity/" + textureName.toLowerCase() + ".png");
         }

         return AssetManager.getTexture(textureName);
      } else {
         return super.getTexture();
      }
   }
}
