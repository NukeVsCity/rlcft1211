   /** 1.12 dimension id of a level (0 overworld, -1 nether, 1 end) for the dimension lists; other dimensions get a stable hash. */
   public static int dimensionId(net.minecraft.world.level.Level level) {
      var key = level.dimension();
      if (key == net.minecraft.world.level.Level.OVERWORLD) return 0;
      if (key == net.minecraft.world.level.Level.NETHER) return -1;
      if (key == net.minecraft.world.level.Level.END) return 1;
      return key.location().hashCode();
   }
