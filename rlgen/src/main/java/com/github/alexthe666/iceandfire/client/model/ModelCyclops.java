   public void setRotationAngles(float f, float f1, float f2, float f3, float f4, float f5, EntityCyclops entity) {
      float speed_walk = 0.2F;
      float speed_idle = 0.05F;
      float degree_walk = 0.75F;
      float degree_idle = 0.5F;
      this.walk(this.rightleg, speed_walk, degree_walk * -0.75F, true, 0.0F, 0.0F, f, f1);
      this.walk(this.leftleg, speed_walk, degree_walk * -0.75F, false, 0.0F, 0.0F, f, f1);
      this.walk(this.rightleg2, speed_walk, degree_walk * -0.5F, true, 1.0F, -0.3F, f, f1);
      this.walk(this.leftleg2, speed_walk, degree_walk * -0.5F, false, 1.0F, 0.3F, f, f1);
      this.walk(this.rightarm, speed_walk, degree_walk * -0.75F, false, 0.0F, 0.0F, f, f1);
      this.walk(this.leftarm, speed_walk, degree_walk * -0.75F, true, 0.0F, 0.0F, f, f1);
      this.walk(this.rightarm2, speed_walk, degree_walk * -0.5F, false, 1.0F, -0.3F, f, f1);
      this.walk(this.leftarm2, speed_walk, degree_walk * -0.5F, true, 1.0F, 0.3F, f, f1);
      this.swing(this.body, speed_walk, degree_walk * -0.5F, false, 0.0F, 0.0F, f, f1);
      this.swing(this.UpperBody, speed_walk, degree_walk * -0.25F, true, 0.0F, 0.0F, f, f1);
      this.swing(this.Belly, speed_walk, degree_walk * -0.25F, false, 0.0F, 0.0F, f, f1);
      this.walk(this.UpperBody, speed_idle, degree_idle * -0.1F, true, 0.0F, -0.1F, (float)entity.tickCount, 1.0F);
      this.flap(this.leftarm, speed_idle, degree_idle * -0.1F, true, 0.0F, 0.0F, (float)entity.tickCount, 1.0F);
      this.flap(this.rightarm, speed_idle, degree_idle * -0.1F, false, 0.0F, 0.0F, (float)entity.tickCount, 1.0F);
      this.flap(this.leftarm2, speed_idle, degree_idle * -0.1F, true, 0.0F, -0.1F, (float)entity.tickCount, 1.0F);
      this.flap(this.rightarm2, speed_idle, degree_idle * -0.1F, false, 0.0F, -0.1F, (float)entity.tickCount, 1.0F);
      if (entity.getAnimation() != EntityCyclops.ANIMATION_EATPLAYER) {
         this.faceTarget(f3, f4, 1.0F, new AdvancedModelRenderer[]{this.Head});
      }

      this.walk(this.Jaw, speed_idle, degree_idle * -0.15F, true, 0.0F, -0.1F, (float)entity.tickCount, 1.0F);
      if (entity != null) {
         Vec3 vec3d = ((Entity)entity).getEyePosition(0.0F);
         Vec3 vec3d1 = ((Entity)entity).getEyePosition(0.0F);
         double d0 = vec3d.y - vec3d1.y;
         if (d0 > 0.0) {
            this.Eye.rotationPointY = -4.1F;
         } else {
            this.Eye.rotationPointY = -5.1F;
         }

         Vec3 vec3d2 = ((Entity)entity).getViewVector(0.0F);
         vec3d2 = new Vec3(vec3d2.x, 0.0, vec3d2.z);
         Vec3 vec3d3 = new Vec3(vec3d1.x - vec3d.x, 0.0, vec3d1.z - vec3d.z)
            .normalize()
            .yRot((float) (Math.PI / 2));
         double d1 = vec3d2.dot(vec3d3);
         this.Eye.rotationPointX = Mth.sqrt((float)Math.abs(d1)) * 2.0F * (float)Math.signum(d1);
      }
   }

